const COLORS = ['#0A6FB0', '#0B2236', '#B85A0E', '#1F7A4D', '#13314A'];

/** Rows in the format the home page uses: [text, name, place, tag, initial, colour, cardWidth]. */
export function reviewRows(lang: string) {
  const ru = lang === 'ru';
  return REVIEWS.map((r, i) => {
    const name = ru ? r.nameRu : r.name;
    return [r.text, name, '', ru ? r.tagRu : r.tag, name[0], COLORS[i % COLORS.length]];
  });
}

/** Wider cards for long reviews so short ones are not stretched with empty space. */
export const cardWidth = (text: string) => (text.length > 400 ? '620px' : text.length > 200 ? '460px' : '380px');
